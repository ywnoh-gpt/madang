/* Build a single file for the Google Apps Script editor; no external dependencies. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'apps-script/Code.gs'), 'utf8');
const html = fs.readFileSync(path.join(root, 'apps-script/Index.html'), 'utf8');
const replacement = 'HtmlService.createHtmlOutput(MADANG_HTML_)';
const bundledSource = source.replaceAll("HtmlService.createHtmlOutputFromFile('Index')", replacement);
if (bundledSource === source) throw new Error('HTML entrypoint missing: update the bundler.');
const bundle = '/* Generated by node tools/build_apps_script.cjs. Paste this entire file into Code.gs. */\n'
  + 'var MADANG_HTML_ = ' + JSON.stringify(html) + ';\n\n' + bundledSource;
new vm.Script(bundle, {filename:'Madang.gs'});
const output = path.join(root, 'dist');
fs.mkdirSync(output, {recursive:true});
fs.writeFileSync(path.join(output, 'Madang.gs'), bundle);
console.log('Built dist/Madang.gs (' + Buffer.byteLength(bundle) + ' bytes); original HTML is embedded.');
